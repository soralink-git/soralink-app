create temporary table sl_media_test(a uuid,b uuid,card uuid,path text);
insert into sl_media_test(a,b) values(gen_random_uuid(),gen_random_uuid());
insert into auth.users(id,email) select a,'media-test-a@example.invalid' from sl_media_test union all select b,'media-test-b@example.invalid' from sl_media_test;
grant select,update on sl_media_test to authenticated,anon;
create function pg_temp.media_assert(ok boolean,message text) returns void language plpgsql as $$begin if not coalesce(ok,false) then raise exception 'FAILED: %',message;end if;end;$$;
set local role authenticated;
select set_config('request.jwt.claims',jsonb_build_object('sub',a,'aal','aal1','role','authenticated')::text,true) from sl_media_test;
update sl_media_test set card=public.sl_create_card('Media Test');
update sl_media_test set path=card||'/identity/'||gen_random_uuid()||'.png';
select pg_temp.media_assert(sl_private.media_upload_allowed(path),'Owner can upload identity') from sl_media_test;
select pg_temp.media_assert(not sl_private.media_upload_allowed(replace(path,'/identity/','/gallery/')),'Social cannot upload gallery') from sl_media_test;
select set_config('request.jwt.claims',jsonb_build_object('sub',b,'aal','aal1','role','authenticated')::text,true) from sl_media_test;
select pg_temp.media_assert(not sl_private.media_upload_allowed(path),'Another client cannot upload') from sl_media_test;
select pg_temp.media_assert(not sl_private.media_owner(path),'Another client cannot read draft media') from sl_media_test;
reset role;
insert into public.sl_blocks(card_id,module,enabled,content) select card,'identity',true,jsonb_build_object('image','/media/'||path) from sl_media_test;
set local role anon;
select set_config('request.jwt.claims','{}',true);
select pg_temp.media_assert(not sl_private.media_published(path),'Draft asset is private') from sl_media_test;
reset role;
update public.sl_access set status='published' where card_id=(select card from sl_media_test);
set local role anon;
select pg_temp.media_assert(sl_private.media_published(path),'Published referenced asset is visible') from sl_media_test;
reset role;
update public.sl_blocks set enabled=false where card_id=(select card from sl_media_test);
set local role anon;
select pg_temp.media_assert(not sl_private.media_published(path),'Disabled asset becomes private') from sl_media_test;
reset role;
select pg_temp.media_assert(sl_private.media_parts('../invalid') is null,'Path traversal rejected');
select pg_temp.media_assert(sl_private.media_parts(replace(path,'.png','.pdf')) is null,'PDF in image module rejected') from sl_media_test;
